const fs = require('fs');
const path = require('path');
const config = require('./config.js');

// Derive unique folders from config
const FOLDER_MAP = {};
const EXTENSIONS = {};

for (const appKey in config.apps) {
    const app = config.apps[appKey];
    FOLDER_MAP[app.folder] = app.parent;
    EXTENSIONS[app.folder] = config.extensions[app.type];
}

const FOLDERS = Object.keys(FOLDER_MAP);

function getFilesForFolder(folder) {
  const parentDir = FOLDER_MAP[folder];
  const dirPath = path.join(__dirname, parentDir, folder);
  if (!fs.existsSync(dirPath)) {
    return [];
  }
  
  if (folder.toLowerCase().includes('backup') || dirPath.toLowerCase().includes('backup')) {
    console.log(`[Generator] Ignoring backup folder: ${folder}`);
    return [];
  }
  
  try {
    const files = fs.readdirSync(dirPath);
    const exts = EXTENSIONS[folder] || [];
    
    return files
      .filter(file => {
        if (file.toLowerCase().includes('backup')) return false;
        try {
          const fullPath = path.join(dirPath, file);
          const stat = fs.statSync(fullPath);
          if (!stat.isFile()) return false;

          const ext = path.extname(file).toLowerCase();
          return exts.includes(ext);
        } catch(e) { return false; }
      })
      .map(file => {
        // Construct the URL path (e.g. input/videos/filename.mp4)
        if (parentDir === 'input') {
           return `input/${folder}/${file}`;
        }
        return `assets/${folder}/${file}`;
      });
  } catch (err) {
    console.error(`[Generator] Error reading directory ${dirPath}:`, err);
    return [];
  }
}

function generateFilesJs() {
  const result = {};
  
  FOLDERS.forEach(folder => {
    result[folder] = getFilesForFolder(folder);
  });

  const fileContent = `// Auto-generated by backend\nwindow.collageFiles = ${JSON.stringify(result, null, 2)};`;
  const outputPath = path.join(__dirname, 'files.js');
  
  fs.writeFileSync(outputPath, fileContent, 'utf8');
  console.log(`[Generator] Created files.js successfully.`);
}

module.exports = {
  getFilesForFolder,
  generateFilesJs,
  FOLDERS,
  FOLDER_MAP
};
